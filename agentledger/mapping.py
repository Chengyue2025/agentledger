def obligations_for(rule_id: str) -> list[dict[str, str]]:
    out = []
    for oid in RULE_OBLIGATIONS.get(rule_id, []):
        meta = OBLIGATIONS.get(oid)
        if meta:
            out.append({"id": oid, **meta})
    return out


def obligations_for_findings(findings: Iterable[Finding]) -> dict[str, dict[str, str]]:
    """汇总本次扫描触及的全部义务（去重）。"""
    seen: dict[str, dict[str, str]] = {}
    for f in findings:
        for ob in obligations_for(f.rule_id):
            seen.setdefault(ob["id"], {k: ob[k] for k in ("id", "title", "quote", "scope")})
    return seen


def readiness_gap(findings: Iterable[Finding]) -> dict[str, list[str]]:
    """义务 → 未满足该义务的发现项列表。用于生成整改台账。"""
    gaps: dict[str, list[str]] = {}
    for f in findings:
        for oid in RULE_OBLIGATIONS.get(f.rule_id, []):
            gaps.setdefault(oid, []).append(f"{f.rule_id} @ {f.location()}")
    return gaps


